/// Generates the documentation data of the showcase: the API reference,
/// from the public API of the oito2_ui packages and their doc comments,
/// and copies of the packages' changelogs.
///
/// Usage: `dart run tool/generate_docs.dart [--check]`, from the workspace
/// root. Without arguments it writes
/// `example/lib/src/docs/api_reference.g.dart` and
/// `example/assets/docs/changelog/<package>.md`; with `--check` it writes
/// nothing and exits with code 1 when any of them is out of date.
library;

import 'dart:io';

import 'package:analyzer/dart/analysis/analysis_context_collection.dart';
import 'package:analyzer/dart/analysis/results.dart';
import 'package:analyzer/dart/element/element.dart';
import 'package:analyzer/dart/element/nullability_suffix.dart';
import 'package:analyzer/dart/element/type.dart';

/// The packages whose public libraries are documented, in display order.
const _packages = [
  'oito2_ui',
  'oito2_ui_window',
  'oito2_ui_settings',
  'oito2_ui_syntax',
  'oito2_ui_themes',
  'oito2_ui_extras',
  'oito2_ui_files',
];

/// The generated API reference, relative to the workspace root.
const _output = 'example/lib/src/docs/api_reference.g.dart';

/// The folder of the changelog copies, relative to the workspace root.
const _changelogs = 'example/assets/docs/changelog';

/// Members every widget, state or object inherits, never listed.
const _skippedMembers = {
  'key',
  'hashCode',
  'runtimeType',
  'build',
  'createState',
  'createElement',
  'createRenderObject',
  'updateRenderObject',
  'debugFillProperties',
  'toString',
  'noSuchMethod',
};

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final root = Directory.current.absolute.path;
  final libraries = [
    for (final package in _packages)
      '$root/packages/$package/lib/$package.dart',
  ];
  final collection = AnalysisContextCollection(includedPaths: libraries);
  final buffer = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
    ..writeln('// Generated by tool/generate_docs.dart from the doc')
    ..writeln('// comments of the oito2_ui packages.')
    ..writeln('// dart format off')
    ..writeln()
    ..writeln("import 'api_model.dart';")
    ..writeln()
    ..writeln('/// The public API of the oito2_ui packages, by name.')
    ..writeln('const Map<String, ApiEntry> apiReference = {');
  for (var i = 0; i < _packages.length; i++) {
    final path = libraries[i];
    final session = collection.contextFor(path).currentSession;
    final result = await session.getResolvedLibrary(path);
    if (result is! ResolvedLibraryResult) {
      stderr.writeln('Could not resolve $path');
      exit(2);
    }
    final names = result.element.exportNamespace.definedNames2;
    final sorted = names.keys.where((name) => !name.contains('.')).toList()
      ..sort();
    for (final name in sorted) {
      final element = names[name]!;
      // Re-exports of other packages, such as the Lucide icons, aren't
      // documented here.
      final uri = element.library?.uri;
      if (uri == null || !_packages.contains(uri.pathSegments.first)) {
        continue;
      }
      final entry = _entry(element, _packages[i]);
      if (entry != null) buffer.writeln('  ${_literal(name)}: $entry,');
    }
  }
  buffer.writeln('};');
  final outputs = <String, String>{
    _output: buffer.toString(),
    for (final package in _packages)
      '$_changelogs/$package.md': File('$root/packages/$package/CHANGELOG.md')
          .readAsStringSync(),
  };
  var stale = false;
  for (final MapEntry(key: path, value: content) in outputs.entries) {
    final file = File('$root/$path');
    final current = file.existsSync() ? file.readAsStringSync() : null;
    if (current == content) continue;
    if (check) {
      stderr.writeln('$path is out of date.');
      stale = true;
    } else {
      file
        ..createSync(recursive: true)
        ..writeAsStringSync(content);
      stdout.writeln('Wrote $path.');
    }
  }
  if (stale) {
    stderr.writeln('Run dart run tool/generate_docs.dart to update them.');
    exit(1);
  }
  if (check) stdout.writeln('The documentation data is up to date.');
}

/// Returns the `ApiEntry(...)` source of [element] from [package], or null
/// for elements the reference doesn't list.
String? _entry(Element element, String package) {
  final doc = _doc(element);
  String entry(
    String kind, {
    List<String> constructors = const [],
    List<String> properties = const [],
    List<String> methods = const [],
    List<String> values = const [],
    String signature = '',
  }) =>
      'ApiEntry(kind: ${_literal(kind)}, package: ${_literal(package)}, '
      'doc: ${_literal(doc)}, signature: ${_literal(signature)}, '
      'constructors: [${constructors.join(', ')}], '
      'properties: [${properties.join(', ')}], '
      'methods: [${methods.join(', ')}], '
      'values: [${values.join(', ')}])';
  switch (element) {
    case EnumElement():
      return entry(
        'enum',
        values: [
          for (final value in element.constants)
            if (value.name case final name?) _member(name, '', value),
        ],
        methods: _methods(element),
      );
    case ClassElement() || MixinElement() || ExtensionTypeElement():
      final interface = element as InterfaceElement;
      final constructors = <String>[];
      final parameterNames = <String>{};
      for (final constructor in interface.constructors) {
        final name = constructor.name;
        if (name == null || name.startsWith('_') || constructor.isPrivate) {
          continue;
        }
        final parameters = [
          for (final parameter in constructor.formalParameters)
            if (parameter is! SuperFormalParameterElement ||
                parameter.name != 'key')
              _parameter(parameter),
        ];
        parameterNames.addAll(
          constructor.formalParameters.map((p) => p.name ?? ''),
        );
        final title = name == 'new'
            ? interface.name!
            : '${interface.name}.$name';
        constructors.add(
          'ApiConstructor(name: ${_literal(title)}, '
          'doc: ${_literal(_doc(constructor))}, '
          'isConst: ${constructor.isConst}, '
          'isFactory: ${constructor.isFactory}, '
          'parameters: [${parameters.join(', ')}])',
        );
      }
      final kind = switch (element) {
        MixinElement() => 'mixin',
        ExtensionTypeElement() => 'extension type',
        ClassElement(isAbstract: true) => 'abstract class',
        _ => 'class',
      };
      return entry(
        kind,
        constructors: constructors,
        properties: _properties(interface, parameterNames),
        methods: _methods(interface),
      );
    case TypeAliasElement():
      return entry('typedef', signature: _type(element.aliasedType));
    case TopLevelFunctionElement():
      return entry('function', signature: _functionSignature(element));
    case TopLevelVariableElement():
      return entry(
        element.isConst ? 'constant' : 'variable',
        signature: _type(element.type),
      );
    case GetterElement():
      return entry('getter', signature: _type(element.returnType));
    case ExtensionElement():
      return entry('extension', methods: _methods(element));
    default:
      return null;
  }
}

/// Returns the `ApiParameter(...)` source of [parameter], documented by the
/// field it initializes when it has no doc of its own.
String _parameter(FormalParameterElement parameter) {
  var doc = _doc(parameter);
  if (doc.isEmpty && parameter is FieldFormalParameterElement) {
    final field = parameter.field;
    if (field != null) doc = _doc(field);
  }
  return 'ApiParameter(name: ${_literal(parameter.name ?? '')}, '
      'type: ${_literal(_type(parameter.type))}, '
      'isRequired: ${parameter.isRequired}, '
      'isNamed: ${parameter.isNamed}, '
      'defaultValue: ${_literal(_defaultValue(parameter))}, '
      'doc: ${_literal(doc)})';
}

/// Returns the source of the default value of [parameter], or its value
/// when the source names a private constant, which readers can't look up;
/// empty when that value isn't a number, a string or a boolean.
String _defaultValue(FormalParameterElement parameter) {
  final code = parameter.defaultValueCode ?? '';
  if (!RegExp(r'(^|[^\w])_\w').hasMatch(code)) return code;
  final value = parameter.computeConstantValue();
  if (value == null) return '';
  final number = value.toDoubleValue() ?? value.toIntValue();
  if (number != null) {
    return number is double && number == number.roundToDouble()
        ? number.toStringAsFixed(1)
        : '$number';
  }
  final text = value.toStringValue();
  if (text != null) return "'$text'";
  return value.toBoolValue()?.toString() ?? '';
}

/// Returns the documented public fields and getters of [element] that no
/// constructor parameter in [parameterNames] already describes.
List<String> _properties(InterfaceElement element, Set<String> parameterNames) {
  final result = <String>[];
  final seen = <String>{};
  for (final field in element.fields) {
    final name = field.name;
    if (name == null ||
        field.isPrivate ||
        parameterNames.contains(name) ||
        _skippedMembers.contains(name) ||
        _isOverride(field) ||
        !seen.add(name)) {
      continue;
    }
    if (element is EnumElement && field.isEnumConstant) continue;
    final getter = field.getter;
    final doc = _doc(field).isNotEmpty
        ? _doc(field)
        : (getter == null ? '' : _doc(getter));
    if (doc.isEmpty) continue;
    final prefix = field.isStatic ? 'static ' : '';
    result.add(_member(name, '$prefix${_type(field.type)}', field, doc: doc));
  }
  return result;
}

/// Returns the documented public methods of [element], static ones
/// included, without the overrides of inherited members.
List<String> _methods(InstanceElement element) {
  final result = <String>[];
  for (final method in element.methods) {
    final name = method.name;
    if (name == null ||
        method.isPrivate ||
        method.isOperator ||
        _skippedMembers.contains(name) ||
        _isOverride(method)) {
      continue;
    }
    final doc = _doc(method);
    if (doc.isEmpty) continue;
    final prefix = method.isStatic ? 'static ' : '';
    result.add(
      _member(name, '$prefix${_functionSignature(method)}', method, doc: doc),
    );
  }
  return result;
}

/// Returns the `ApiMember(...)` source of [element] named [name].
String _member(String name, String signature, Element element, {String? doc}) =>
    'ApiMember(name: ${_literal(name)}, signature: ${_literal(signature)}, '
    'doc: ${_literal(doc ?? _doc(element))})';

/// Returns `name(parameters) → return type` for [function].
String _functionSignature(ExecutableElement function) {
  final parameters = function.formalParameters
      .map((p) => '${_type(p.type)} ${p.name}')
      .join(', ');
  return '${function.name}($parameters) → ${_type(function.returnType)}';
}

/// Returns the name of [type] as written in the source: through its
/// typedef, such as `ValueChanged<double>?`, when it has one.
String _type(DartType type) {
  final alias = type.alias;
  if (alias == null) return type.toString();
  final arguments = alias.typeArguments;
  final suffix = type.nullabilitySuffix == NullabilitySuffix.question
      ? '?'
      : '';
  final generic = arguments.isEmpty
      ? ''
      : '<${arguments.map(_type).join(', ')}>';
  return '${alias.element.name}$generic$suffix';
}

/// Whether [element] carries an `@override` annotation.
bool _isOverride(Element element) =>
    element.metadata.annotations.any((annotation) => annotation.isOverride);

/// Returns the doc comment of [element] without its `///` markers.
String _doc(Element element) {
  final raw = element.documentationComment;
  if (raw == null) return '';
  return raw
      .split('\n')
      .map((line) => line.trimLeft().replaceFirst(RegExp(r'^/// ?'), ''))
      .join('\n')
      .trim();
}

/// Returns [text] as a single-quoted Dart string literal.
String _literal(String text) {
  final escaped = text
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}
